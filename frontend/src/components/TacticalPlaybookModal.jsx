import React, { useState, useEffect } from 'react';
import {
  X,
  ShieldAlert,
  DollarSign,
  Clock,
  FileCheck,
  CheckCircle2,
  Download,
  AlertTriangle,
  ArrowRight,
  BookOpen,
} from 'lucide-react';
import { api } from '../api/client';

export default function TacticalPlaybookModal({
  isOpen,
  onClose,
  initialPlaybookId = null,
  isInline = false,
}) {
  const [playbooks, setPlaybooks] = useState([]);
  const [selectedPlaybook, setSelectedPlaybook] = useState(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    if (!isOpen && !isInline) return;
    setLoading(true);
    api.getPlaybooks()
      .then((data) => {
        setPlaybooks(data || []);
        if (data && data.length > 0) {
          const matched = initialPlaybookId
            ? data.find((p) => p.playbook_id === initialPlaybookId) || data[0]
            : data[0];
          setSelectedPlaybook(matched);
        }
      })
      .catch((err) => console.error('Failed to load operational playbooks:', err))
      .finally(() => setLoading(false));
  }, [isOpen, initialPlaybookId, isInline]);

  if (!isOpen && !isInline) return null;

  const handleDownloadBrief = () => {
    if (!selectedPlaybook) return;
    const content = `# GEOSENTINEL TACTICAL MITIGATION DIRECTIVE
CLASSIFICATION: PROPRIETARY // EXECUTIVE DECISION SUPPORT
TIMESTAMP: ${new Date().toISOString()}

## PLAYBOOK: ${selectedPlaybook.title}
CATEGORY: ${selectedPlaybook.category}
THEATER: ${selectedPlaybook.threat_theater}
TRIGGER: ${selectedPlaybook.trigger_threshold}

### 1. EXECUTIVE SUMMARY
${selectedPlaybook.executive_summary}

### 2. QUANTIFIED OPERATIONAL & FINANCIAL IMPACT
- Schedule Variance: ${selectedPlaybook.quantified_impact?.schedule_variance}
- Direct Cost Delta: ${selectedPlaybook.quantified_impact?.fuel_or_cost_delta}
- Insurance Surcharge Impact: ${selectedPlaybook.quantified_impact?.insurance_surcharge}
- Total Net Variance: ${selectedPlaybook.quantified_impact?.total_financial_variance}
- Threat Vulnerability Reduction: ${selectedPlaybook.quantified_impact?.threat_reduction_pct}

### 3. RECOMMENDED STRATEGIC DIRECTIVE
${selectedPlaybook.recommended_option}

### 4. PRESCRIPTIVE ACTION CHECKLIST
${(selectedPlaybook.prescriptive_action_plan || [])
  .map(
    (step) =>
      `[ ] Step ${step.step_number} (${step.operational_phase} - ${step.timeframe})\n    Team: ${step.responsible_team}\n    Action: ${step.directive}`
  )
  .join('\n\n')}

---
Generated by GeoSentinel AI Global Threat Operations Center (GTOC)
`;

    const blob = new Blob([content], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `GeoSentinel_Playbook_${selectedPlaybook.playbook_id}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const contentBlock = (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 bg-[#111C2D] p-5 rounded-xl border border-slate-800/80 shadow-sm">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-xl bg-indigo-500/15 border border-indigo-500/30 flex items-center justify-center text-indigo-400">
            <BookOpen className="w-5 h-5" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h2 className="text-base font-bold font-mono text-slate-100 uppercase tracking-wider">
                Action Playbooks &amp; Contingency Directives
              </h2>
              <span className="px-2 py-0.5 rounded text-[10px] font-mono font-bold bg-indigo-950 text-indigo-300 border border-indigo-700/50">
                SOP PROTOCOLS
              </span>
            </div>
            <p className="text-xs text-slate-400 font-sans">
              Prescriptive operational checklists, quantified financial variance, and supply-chain continuity playbooks.
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleDownloadBrief}
            disabled={!selectedPlaybook}
            className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold rounded-lg bg-indigo-600 hover:bg-indigo-500 text-white shadow-md transition-all font-mono disabled:opacity-50"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Export Directive (.MD)</span>
          </button>
          {!isInline && onClose && (
            <button
              onClick={onClose}
              className="p-1.5 text-slate-400 hover:text-white rounded-lg bg-slate-850 border border-slate-800 transition-colors"
            >
              <X className="w-4 h-4" />
            </button>
          )}
        </div>
      </div>

      {loading ? (
        <div className="py-20 text-center text-indigo-400 font-mono text-xs animate-pulse">
          Loading operational playbooks...
        </div>
      ) : (
        <div className="space-y-5">
          {/* Playbook Tabs */}
          <div className="flex flex-wrap gap-2 pb-1 border-b border-slate-800">
            {playbooks.map((pb) => (
              <button
                key={pb.playbook_id}
                onClick={() => setSelectedPlaybook(pb)}
                className={`px-3 py-2 rounded-lg text-xs font-mono font-bold transition-all flex items-center gap-2 ${
                  selectedPlaybook?.playbook_id === pb.playbook_id
                    ? 'bg-indigo-500/20 text-indigo-300 border border-indigo-500/40 shadow-sm'
                    : 'bg-[#111C2D] text-slate-400 border border-slate-800 hover:text-slate-200'
                }`}
              >
                <span>{pb.title}</span>
              </button>
            ))}
          </div>

          {selectedPlaybook && (
            <div className="space-y-5 animate-fadeIn">
              {/* Executive Summary Card */}
              <div className="bg-[#111C2D] p-5 rounded-xl border border-slate-800/80 shadow-sm space-y-3">
                <div className="flex items-center justify-between text-xs font-mono">
                  <span className="text-slate-400">Theater: <strong className="text-slate-200">{selectedPlaybook.threat_theater}</strong></span>
                  <span className="text-amber-400">Trigger: {selectedPlaybook.trigger_threshold}</span>
                </div>
                <h3 className="text-sm font-bold text-slate-100">{selectedPlaybook.title}</h3>
                <p className="text-xs text-slate-300 leading-relaxed font-sans">
                  {selectedPlaybook.executive_summary}
                </p>
              </div>

              {/* Quantified Variance Grid */}
              {selectedPlaybook.quantified_impact && (
                <div className="grid grid-cols-2 md:grid-cols-4 gap-3">
                  <div className="bg-[#111C2D] p-3.5 rounded-xl border border-slate-800/80">
                    <span className="text-[10px] font-mono text-slate-400 block mb-1">Schedule Delta</span>
                    <span className="text-sm font-mono font-bold text-amber-400">
                      {selectedPlaybook.quantified_impact.schedule_variance}
                    </span>
                  </div>
                  <div className="bg-[#111C2D] p-3.5 rounded-xl border border-slate-800/80">
                    <span className="text-[10px] font-mono text-slate-400 block mb-1">Direct Cost Delta</span>
                    <span className="text-sm font-mono font-bold text-rose-400">
                      {selectedPlaybook.quantified_impact.fuel_or_cost_delta}
                    </span>
                  </div>
                  <div className="bg-[#111C2D] p-3.5 rounded-xl border border-slate-800/80">
                    <span className="text-[10px] font-mono text-slate-400 block mb-1">Insurance Impact</span>
                    <span className="text-sm font-mono font-bold text-slate-200">
                      {selectedPlaybook.quantified_impact.insurance_surcharge}
                    </span>
                  </div>
                  <div className="bg-[#111C2D] p-3.5 rounded-xl border border-slate-800/80">
                    <span className="text-[10px] font-mono text-slate-400 block mb-1">Threat Reduction</span>
                    <span className="text-sm font-mono font-bold text-emerald-400">
                      {selectedPlaybook.quantified_impact.threat_reduction_pct}
                    </span>
                  </div>
                </div>
              )}

              {/* Recommended Directive */}
              <div className="bg-sky-500/10 p-4 rounded-xl border border-sky-500/30 text-xs text-sky-200">
                <span className="font-mono font-bold block mb-1 text-sky-300">RECOMMENDED DIRECTIVE:</span>
                <p className="leading-relaxed font-sans">{selectedPlaybook.recommended_option}</p>
              </div>

              {/* Prescriptive Action Steps */}
              {selectedPlaybook.prescriptive_action_plan && (
                <div className="bg-[#111C2D] p-5 rounded-xl border border-slate-800/80 shadow-sm space-y-3">
                  <div className="text-xs font-mono font-bold text-slate-200 uppercase tracking-wider mb-2">
                    Prescriptive Action Checklist
                  </div>
                  <div className="space-y-2.5">
                    {selectedPlaybook.prescriptive_action_plan.map((step, idx) => (
                      <div
                        key={idx}
                        className="p-3 rounded-lg bg-[#0D1422] border border-slate-800 flex items-start gap-3"
                      >
                        <div className="w-5 h-5 rounded-full bg-indigo-500/20 text-indigo-400 text-[11px] font-mono font-bold flex items-center justify-center shrink-0 mt-0.5">
                          {step.step_number || idx + 1}
                        </div>
                        <div className="space-y-1">
                          <div className="flex items-center gap-2 text-xs font-mono">
                            <span className="font-semibold text-slate-200">{step.operational_phase}</span>
                            <span className="text-slate-500">&bull;</span>
                            <span className="text-sky-400">{step.responsible_team}</span>
                            <span className="text-slate-500">&bull;</span>
                            <span className="text-amber-400">{step.timeframe}</span>
                          </div>
                          <p className="text-xs text-slate-300 font-sans leading-relaxed">{step.directive}</p>
                        </div>
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </div>
          )}
        </div>
      )}
    </div>
  );

  if (isInline) {
    return contentBlock;
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-6 bg-black/85 backdrop-blur-md overflow-y-auto font-sans">
      <div className="bg-[#0D1422] w-full max-w-4xl rounded-2xl border border-slate-800 shadow-2xl p-6 overflow-hidden flex flex-col max-h-[90vh]">
        {contentBlock}
      </div>
    </div>
  );
}
